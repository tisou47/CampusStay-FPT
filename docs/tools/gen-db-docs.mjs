// Generates the logical ERD diagrams (docs/diagrams/erd-*.mmd) and the table catalogue of Report 4
// (docs/reports/src/_db-design.md) from the database itself, so the ERD and the descriptions match the
// Flyway schema. Input: docs/reports/data/dbmeta.json (information_schema of a migrated database) and
// docs/reports/data/tables.json (one description per table).
//
//   node docs/tools/gen-db-docs.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const meta = JSON.parse(fs.readFileSync(path.join(root, 'docs/reports/data/dbmeta.json'), 'utf8'));
const desc = JSON.parse(fs.readFileSync(path.join(root, 'docs/reports/data/tables.json'), 'utf8'));

const AREAS = [
  ['auth', 'Accounts and access (AUTH)'],
  ['cfg', 'Settings and Terms (CFG)'],
  ['inv', 'Inventory: Blocks, Rooms, Beds, furniture, door codes (INV)'],
  ['app', 'Applications (APP)'],
  ['asg', 'Assignment and residence (ASG)'],
  ['bil', 'Billing and Utility (BIL)'],
  ['req', 'Requests, routing and escalations (REQ)'],
  ['mnt', 'Maintenance and inspections (MNT)'],
  ['ntf', 'Notifications and announcements (NTF)'],
  ['shared', 'Shared: Audit Log and files'],
];
const MAIN = ['auth_user', 'auth_student', 'inv_building', 'inv_room', 'inv_bed', 'inv_furniture_item', 'inv_door_code',
  'cfg_term', 'cfg_room_type', 'cfg_room_class', 'cfg_term_price', 'cfg_term_request', 'app_application', 'asg_run',
  'asg_allocation', 'asg_stay', 'asg_check_out', 'asg_termination', 'bil_invoice', 'bil_payment_claim', 'bil_payment',
  'bil_meter_reading', 'req_room_change', 'req_swap', 'req_stay_request', 'req_room_class_change', 'mnt_request',
  'ntf_notification', 'ntf_announcement'];
// Actor columns (who did what) reference auth_user from almost every table; the diagrams leave them out.
const OWNER_COLS = new Set(['student_id', 'user_id', 'reporter_id', 'assignee_id', 'owner_id', 'inspector_id', 'invitee_student_id']);
const KEY_COLS = /^(code|status|type|kind|name|label|amount|price|role|email|level|title|student_code|gender|stage|source|renewal|urgency|category|committed_terms|terms_used|verification|floor_no|asset_code|deposit_amount|term_price|due_at|stay_start|stay_end|period_start|result|reason|grp|surcharge_rate|beds|base_price|audience|event_key|kind|outcome|extra_terms)$/;

const tables = new Map(meta.tables.map((t) => [t.name, t]));
const pk = new Map();
for (const p of meta.pks) pk.set(p.t, [...(pk.get(p.t) ?? []), p.c]);
const fks = [];
const seen = new Set();
for (const f of meta.fks) {
  const k = `${f.t}.${f.c}>${f.rt}`;
  if (seen.has(k)) continue;
  seen.add(k);
  fks.push(f);
}
const fkOf = (t) => fks.filter((f) => f.t === t);
const type = (t) => t.replace(/\(.*\)/, '').replace(/ .*/, '').replace('ARRAY', 'array').replace('character', 'char');

function entity(name, all = false, bare = false) {
  const t = tables.get(name);
  if (bare) return `  ${name} {\n    bigint id PK\n  }`;
  const keys = pk.get(name) ?? [];
  const fkCols = new Set(fkOf(name).map((f) => f.c));
  const cols = t.cols.filter((c) => keys.includes(c.c) || (fkCols.has(c.c) && (OWNER_COLS.has(c.c) || !fkOf(name).some((f) => f.c === c.c && f.rt === 'auth_user'))) || KEY_COLS.test(c.c) || all);
  const lines = cols.slice(0, 14).map((c) => {
    const tags = [keys.includes(c.c) ? 'PK' : null, fkCols.has(c.c) ? 'FK' : null].filter(Boolean).join(',');
    return `    ${type(c.t)} ${c.c}${tags ? ' ' + tags : ''}`;
  });
  return `  ${name} {\n${lines.join('\n')}\n  }`;
}
function rel(f) {
  const t = tables.get(f.t);
  const col = t.cols.find((c) => c.c === f.c);
  const keys = pk.get(f.t) ?? [];
  const oneToOne = keys.length === 1 && keys[0] === f.c;
  const left = col?.n ? '|o' : '||';
  return `  ${f.rt} ${left}--${oneToOne ? 'o|' : 'o{'} ${f.t} : "${f.c}"`;
}
function diagram(names, title, withStubs, bare = false) {
  const set = new Set(names);
  const relLines = [];
  const pairs = new Set();
  for (const name of names) {
    for (const f of fkOf(name)) {
      if (f.rt === 'auth_user' && !OWNER_COLS.has(f.c)) continue;
      if (!withStubs && !set.has(f.rt)) continue;
      const key = `${f.rt}>${f.t}`;
      if (pairs.has(key)) continue;
      pairs.add(key);
      relLines.push(rel(f));
    }
  }
  const stubs = [...new Set(relLines.map((l) => l.trim().split(' ')[0]))].filter((n) => !set.has(n));
  return `%% ${title} — generated by docs/tools/gen-db-docs.mjs from the Flyway schema; do not edit by hand.\nerDiagram\n${names.map((n) => entity(n, false, bare)).join('\n')}\n${stubs.map((s) => `  ${s} {\n    bigint id PK\n  }`).join('\n')}\n${relLines.join('\n')}\n`;
}

const outDir = path.join(root, 'docs/diagrams');
fs.writeFileSync(path.join(outDir, 'erd-overview.mmd'), diagram(MAIN, 'Logical ERD: main entities (attributes in the area diagrams)', false, true));
let md = '';
const missing = [];
AREAS.forEach(([prefix, title], i) => {
  const names = meta.tables.map((t) => t.name).filter((n) => n.startsWith(prefix + '_'));
  fs.writeFileSync(path.join(outDir, `erd-${prefix}.mmd`), diagram(names, `Logical ERD: ${title}`, true));
  md += `### 2.${i + 2} ${title}\n\n![Logical ERD: ${title}](../../diagrams/out/erd-${prefix}.png)\n\n`;
  md += '| No | Table | Description | Keys |\n|---|---|---|---|\n';
  names.forEach((n, k) => {
    if (!desc[n]) missing.push(n);
    const keys = `PK: ${(pk.get(n) ?? []).join(', ') || '—'}`;
    const refs = fkOf(n).map((f) => `${f.c} → ${f.rt}`);
    md += `| ${String(k + 1).padStart(2, '0')} | ${n} | ${desc[n] ?? ''} | ${keys}${refs.length ? '<br>FK: ' + refs.join('<br>') : ''} |\n`;
  });
  md += '\n';
});
fs.writeFileSync(path.join(root, 'docs/reports/src/_db-design.md'), md);
console.log(`${meta.tables.length} tables in ${AREAS.length} areas; ERD files written${missing.length ? '; no description: ' + missing.join(', ') : ''}`);
